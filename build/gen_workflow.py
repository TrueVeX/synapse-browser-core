"""Generate .github/workflows/build-windows.yml: a chain of build stages.

Free GitHub runners stop a job after 6 hours, and a Brave Core build takes
much longer on 4 cores. Each stage compiles for about 4 hours, then saves the
whole build folder as an artifact that the next stage restores and resumes.
Run: python build/gen_workflow.py
"""
from pathlib import Path

STAGES = 12
OUT = Path(__file__).resolve().parent.parent / ".github" / "workflows" / "build-windows.yml"

HEADER = """# Generated by build/gen_workflow.py. Edit that file, not this one.
name: SYNAPSE Windows build (Brave Core)

on:
  workflow_dispatch:
    inputs:
      resume_from:
        description: "Run ID whose saved build folder (build-state) stage 1 continues from. Empty = start fresh."
        required: false
        default: ""

permissions:
  contents: read
  actions: write

env:
  ROOT: D:\\s
  BUILD_MINUTES: 225   # compile time per stage; the rest is restore and save

jobs:
"""

STAGE = """  stage-{n}:
{needs}    runs-on: windows-2022
    timeout-minutes: 355
    outputs:
      finished: ${{{{ steps.build.outputs.finished || steps.skip.outputs.finished }}}}
    steps:
      - name: Already finished?
        id: skip
        if: ${{{{ {prev_finished} }}}}
        run: echo "finished=true" >> $env:GITHUB_OUTPUT
      - name: Start clock
        if: ${{{{ !({prev_finished}) }}}}
        run: echo "DEADLINE=$((Get-Date).ToUniversalTime().AddMinutes([int]$env:BUILD_MINUTES).ToString('o'))" >> $env:GITHUB_ENV
      - uses: actions/checkout@v4
        if: ${{{{ !({prev_finished}) }}}}
      - uses: ./.github/actions/prepare
        if: ${{{{ !({prev_finished}) }}}}
{restore}      - name: Build
        id: build
        if: ${{{{ !({prev_finished}) }}}}
        run: ./build/stage.ps1 -Root $env:ROOT -Deadline $env:DEADLINE{fresh}
      - name: Save build folder for the next stage
        if: ${{{{ !({prev_finished}) && steps.build.outputs.finished == 'false' }}}}
        run: |
          7z a -tzip -mx=1 -mmt=on "C:\\state.zip" "$env:ROOT\\*" | Out-Null
          if ($LASTEXITCODE -gt 1) {{ throw "7z failed: $LASTEXITCODE" }}
          Get-Item C:\\state.zip | ForEach-Object {{ "state.zip: {{0:N1}} GB" -f ($_.Length / 1GB) }}
          exit 0  # 7z exit code 1 = warnings only (a few broken links in the tree)
      - uses: actions/upload-artifact@v4
        if: ${{{{ !({prev_finished}) && steps.build.outputs.finished == 'false' }}}}
        with:
          name: build-state
          path: C:\\state.zip
          compression-level: 0
          retention-days: 2
          overwrite: true
      - name: Package SYNAPSE
        if: ${{{{ steps.build.outputs.finished == 'true' }}}}
        run: ./build/package.ps1 -Root $env:ROOT -Dest C:\\dist
      - uses: actions/upload-artifact@v4
        if: ${{{{ steps.build.outputs.finished == 'true' }}}}
        with:
          name: synapse-windows
          path: C:\\dist\\*
          compression-level: 0
          retention-days: 14
"""

RESTORE = """      - uses: actions/download-artifact@v4
        if: ${{{{ !({prev_finished}){cond} }}}}
        with:
          name: build-state
          path: C:\\
{run_id}      - name: Restore build folder
        if: ${{{{ !({prev_finished}){cond} }}}}
        run: |
          7z x -y "-o$env:ROOT" C:\\state.zip | Out-Null
          if ($LASTEXITCODE -gt 1) {{ throw "7z failed: $LASTEXITCODE" }}
          Get-PSDrive -PSProvider FileSystem | ForEach-Object {{ "{{0}}: {{1:N1}} GB free" -f $_.Name, ($_.Free / 1GB) }}
          Remove-Item C:\\state.zip
          exit 0
"""


def main() -> None:
    parts = [HEADER]
    for n in range(1, STAGES + 1):
        if n == 1:
            # Start fresh, or continue from another run's saved build folder.
            needs, prev = "", "false"
            restore = RESTORE.format(
                prev_finished=prev, cond=" && inputs.resume_from != ''",
                run_id="          run-id: ${{ inputs.resume_from }}\n"
                       "          github-token: ${{ github.token }}\n")
            fresh = " -Fresh:$('${{ inputs.resume_from }}' -eq '')"
        else:
            needs = f"    needs: stage-{n - 1}\n"
            prev = f"needs.stage-{n - 1}.outputs.finished == 'true'"
            restore = RESTORE.format(prev_finished=prev, cond="", run_id="")
            fresh = ""
        parts.append(STAGE.format(n=n, needs=needs, prev_finished=prev, restore=restore, fresh=fresh))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("".join(parts), encoding="utf-8", newline="\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
